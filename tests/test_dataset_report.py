def test_schema_profile_exact_numbers(tmp_path, messy_fixture_df):
    """Assert exact profile numbers generated by DuckDB profiling engine."""
    db_path = str(tmp_path / "test_profile.duckdb")
    tool = DuckDBTool(db_path)
    tool.load_file = lambda path, name: None  # mock

    # Load cleaned df into DuckDB directly for profiling assertion
    cleaning_res = clean_dataset(messy_fixture_df, "test_table")
    with duckdb.connect(db_path) as conn:
        conn.register("_test_df", cleaning_res.cleaned_df)
        conn.execute('CREATE TABLE "test_table" AS SELECT * FROM _test_df')

    profile = build_schema_profile(db_path, "test_table")
    assert profile["table_name"] == "test_table"
    assert profile["row_count"] == len(cleaning_res.cleaned_df)

    cols = {c["name"]: c for c in profile["columns"]}
    assert "amount" in cols
    assert cols["constant_col"]["is_constant"] is True
    assert cols["id"]["is_candidate_id"] is True


def test_quality_score_raw_vs_clean(messy_fixture_df):
    """Assert raw_score < clean_score and issue detection list."""
    res = clean_dataset(messy_fixture_df, "test_quality")

    raw_score = res.report["raw_score"]
    clean_score = res.report["clean_score"]

    # raw_score must be lower than clean_score due to duplicates, empty rows, and formatting
    assert raw_score < clean_score
    assert len(res.report["issues"]) > 0

    issue_types = [i.get("description", "") for i in res.report["issues"]]
    assert any("duplicate" in desc.lower() for desc in issue_types)


def test_domain_classifier_json_validation_and_fallback():
    """Test domain classifier JSON validation, retry, and heuristic fallback."""
    # Test valid JSON parsing
    valid_json = json.dumps({
        "domain": "Sales",
        "confidence": 0.95,
        "reason": "Contains sales metrics",
        "likely_kpis": ["revenue"],
        "likely_dimensions": ["category"],
        "suggested_questions": ["Q1", "Q2", "Q3", "Q4", "Q5"],
    })
    parsed = _parse_and_validate_json(valid_json)
    assert parsed is not None
    assert parsed["domain"] == "Sales"
    assert len(parsed["suggested_questions"]) == 5

    # Test fallback heuristic
    columns = ["order_id", "revenue", "product_name"]
    dtypes = {"order_id": "BIGINT", "revenue": "DOUBLE", "product_name": "VARCHAR"}
    fb = _fallback_domain_heuristic(columns, dtypes)
    assert fb["domain"] == "Sales"
    assert len(fb["suggested_questions"]) == 5

    # Test mocked LLM fallback trigger
    with patch("app.services.domain_classifier.ChatOllama") as mock_ollama_class:
        mock_instance = MagicMock()
        mock_instance.invoke.side_effect = Exception("LLM connection timeout")
        mock_ollama_class.return_value = mock_instance

        res = classify_domain(columns, dtypes, [])
        assert res["domain"] in ["Sales", "HR", "Healthcare", "Finance", "Marketing", "Inventory", "Education", "Other"]
        assert len(res["suggested_questions"]) == 5


def test_sales_and_hr_fixtures_produce_non_covid_overviews(sales_fixture_df, hr_fixture_df):
    """Assert Sales and HR fixtures each produce non-COVID domain overviews."""
    from app.agents.analyzer import AnalyzerAgent

    analyzer = AnalyzerAgent(model="llama3.2", base_url="http://localhost:11434", webhook_url="")

    # Sales overview test
    sales_overview = {
        "tables": [{
            "name": "sales_data",
            "row_count": len(sales_fixture_df),
            "columns": [{"name": col, "type": "VARCHAR" if col == "product_name" else "DOUBLE"} for col in sales_fixture_df.columns],
            "sample": sales_fixture_df.to_dict(orient="records"),
        }]
    }
    sales_fallback = analyzer._overview_fallback(sales_overview)
    assert "covid" not in sales_fallback["answer"].lower()
    assert "Sales" in sales_fallback["answer"] or "sales_data" in sales_fallback["answer"]

    # HR overview test
    hr_overview = {
        "tables": [{
            "name": "employee_data",
            "row_count": len(hr_fixture_df),
            "columns": [{"name": col, "type": "VARCHAR" if col in ("employee_id", "employee_name", "department", "hire_date") else "BIGINT"} for col in hr_fixture_df.columns],
            "sample": hr_fixture_df.to_dict(orient="records"),
        }]
    }
    hr_fallback = analyzer._overview_fallback(hr_overview)
    assert "covid" not in hr_fallback["answer"].lower()
    assert "Human Resources" in hr_fallback["answer"] or "HR" in hr_fallback["answer"] or "employee_data" in hr_fallback["answer"]
